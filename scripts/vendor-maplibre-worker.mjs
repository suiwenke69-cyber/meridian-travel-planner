/**
 * Vendors the MapLibre GL web worker into `public/`.
 *
 * WHY THIS EXISTS
 * ---------------
 * MapLibre GL does its tile parsing in a web worker. Its published bundle
 * resolves that worker at runtime through `import.meta.url`, which a bundler
 * cannot statically analyse — so under Next.js/webpack the worker never loads
 * and the map renders as an empty canvas with no tiles.
 *
 * The worker and its shared chunk are therefore copied verbatim into `public/`
 * and pointed at explicitly with `setWorkerUrl()` in `components/map/MapCanvas`.
 * They are build outputs, not source: `public/maplibre/` is gitignored and this
 * script runs automatically before `dev` and `build`.
 *
 * If a MapLibre upgrade changes the worker filenames, this script fails loudly
 * rather than shipping a silently blank map.
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'node_modules', 'maplibre-gl', 'dist');
const targetDir = join(root, 'public', 'maplibre');

const FILES = ['maplibre-gl-worker.mjs', 'maplibre-gl-shared.mjs'];

mkdirSync(targetDir, { recursive: true });

const copied = [];
for (const file of FILES) {
  const from = join(sourceDir, file);
  if (!existsSync(from)) {
    console.error(
      `[vendor-maplibre-worker] Missing ${file} in node_modules/maplibre-gl/dist.\n` +
        'The MapLibre package layout changed — update FILES in scripts/vendor-maplibre-worker.mjs.\n' +
        'Without this file the basemap renders blank.',
    );
    process.exit(1);
  }
  copyFileSync(from, join(targetDir, file));
  copied.push(`${file} (${Math.round(readFileSync(from).byteLength / 1024)} kB)`);
}

// A tiny sentinel so the dev server can be checked at a glance.
writeFileSync(
  join(targetDir, 'README.txt'),
  'Generated by scripts/vendor-maplibre-worker.mjs — do not edit, do not commit.\n',
);

console.log(`[vendor-maplibre-worker] vendored: ${copied.join(', ')}`);
